/**
 * Tests for the description/topic plan: coverage gates, empty values,
 * fields the job never generated (whoever wrote them), staleness from the
 * meta and (topics) new posts, quiet channels, switches and missing
 * scopes. No value is protected because a person wrote it.
 */

import { describe, expect, it } from 'vitest';

import { type FieldInput, planField } from './plan.js';

const META = {
  file: '/h/.meta/meta.json',
  generatedAt: '2026-10-10T00:00:00.000Z',
};

const input = (over: Partial<FieldInput> = {}): FieldInput => ({
  field: 'description',
  enabled: true,
  homeDir: '/h',
  homeDirExists: true,
  meta: META,
  canWrite: true,
  current: '',
  lastHumanTs: '100.000000',
  ...over,
});

/** The job generated the field before; `current` is whatever is there now. */
const generatedBefore = (
  current: string,
  over: Record<string, string> = {},
) => ({
  current,
  previous: {
    generatedAt: META.generatedAt,
    lastMessageTs: '100.000000',
    checkedAt: '2026-10-10T01:00:00.000Z',
    ...over,
  },
});

describe('planField', () => {
  it.each<[string, Partial<FieldInput>, string, string]>([
    ['switched off', { enabled: false }, 'skip', 'disabled'],
    ['no home directory', { homeDir: undefined }, 'skip', 'no-home-dir'],
    [
      'home directory missing',
      { homeDirExists: false },
      'skip',
      'home-dir-missing',
    ],
    ['no meta', { meta: undefined }, 'skip', 'no-meta'],
    ['empty description', {}, 'generate', 'empty'],
    ['blank description', { current: '   ' }, 'generate', 'empty'],
    ['empty, no write scope', { canWrite: false }, 'skip', 'missing-scope'],
    [
      'hand-written, never generated by the job',
      { current: 'Hand-written' },
      'generate',
      'new',
    ],
    [
      'never generated, no write scope',
      { current: 'Hand-written', canWrite: false },
      'skip',
      'missing-scope',
    ],
    [
      'edited by a person since the job generated it, meta unchanged',
      generatedBefore('Edited text'),
      'skip',
      'fresh',
    ],
    [
      'edited by a person, meta regenerated since',
      generatedBefore('Edited text', {
        generatedAt: '2026-10-01T00:00:00.000Z',
      }),
      'generate',
      'stale',
    ],
    [
      'emptied by a person since the job generated it',
      generatedBefore(''),
      'generate',
      'empty',
    ],
    [
      'generated from an unsynthesized meta, meta synthesized since',
      { current: 'Job text', previous: { checkedAt: 'x' } },
      'generate',
      'stale',
    ],
    [
      'stale, no write scope',
      {
        ...generatedBefore('Job text', {
          generatedAt: '2026-10-01T00:00:00.000Z',
        }),
        canWrite: false,
      },
      'skip',
      'missing-scope',
    ],
    [
      'meta never synthesized',
      { ...generatedBefore('Job text'), meta: { file: 'm' } },
      'skip',
      'fresh',
    ],
    [
      'meta generatedAt unparseable',
      {
        ...generatedBefore('Job text'),
        meta: { file: 'm', generatedAt: 'soon' },
      },
      'skip',
      'fresh',
    ],
    [
      'description ignores new posts',
      { ...generatedBefore('Job text'), lastHumanTs: '200.000000' },
      'skip',
      'fresh',
    ],
  ])('description: %s', (_label, over, action, reason) => {
    expect(planField(input(over))).toEqual({ action, reason });
  });

  it.each<[string, Partial<FieldInput>, string, string]>([
    ['quiet channel', { lastHumanTs: undefined }, 'skip', 'quiet'],
    [
      'quiet channel with an empty topic',
      { lastHumanTs: undefined, current: '' },
      'skip',
      'quiet',
    ],
    [
      'quiet channel with a hand-written topic',
      { lastHumanTs: undefined, current: 'Hand topic' },
      'skip',
      'quiet',
    ],
    ['empty topic, active channel', {}, 'generate', 'empty'],
    [
      'hand-written topic, active channel',
      { current: 'Hand topic' },
      'generate',
      'new',
    ],
    [
      'generated before, no new posts',
      generatedBefore('Now: x'),
      'skip',
      'fresh',
    ],
    [
      'generated before, a person posted since',
      { ...generatedBefore('Now: x'), lastHumanTs: '200.000000' },
      'generate',
      'stale',
    ],
    [
      'generated before, last post is the one it used',
      { ...generatedBefore('Now: x'), lastHumanTs: '100.000000' },
      'skip',
      'fresh',
    ],
    [
      'generated before without a message mark',
      {
        current: 'Now: x',
        previous: { generatedAt: META.generatedAt, checkedAt: 'x' },
      },
      'generate',
      'stale',
    ],
  ])('topic: %s', (_label, over, action, reason) => {
    expect(planField(input({ field: 'topic', ...over }))).toEqual({
      action,
      reason,
    });
  });
});
